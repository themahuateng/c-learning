/*
 * 练习 3：华氏温度转摄氏温度
 *
 * 任务：输入华氏温度，输出摄氏温度
 * 公式：C = (F - 32) * 5 / 9
 *
 * 提示（先自己想想再看）：
 *   - double 用 %lf
 *   - scanf 里变量要加 &
 *   - 小心整数除法：5/9 在 C 里 = 0！
 */
#include <stdio.h>

int main(void)
{
    double f;   /* 华氏温度（输入） */
    double c;   /* 摄氏温度（结果） */
    printf("请输入华氏温度：");
    /* 第1步：printf 提示用户输入 */
    scanf("%lf", &f);
    /* 第2步：scanf 读取华氏温度 */
    c = (f - 32) * 5 / 9;
    /* 第3步：套公式算出摄氏温度 */
    printf("摄氏温度:%.2lf\n",c);
    /* 第4步：printf 输出结果（保留 2 位小数） */

    return 0;
}
