/* ============================================================
 *  01_pointer_basic.c —— 第 7 课：指针入门 4 件套
 *
 *  这一份要认的 4 个符号:
 *    1. &a   —— a 的"门牌号"（地址）
 *    2. *p   —— 通过门牌号"开门"取/改值
 *    3. int *p —— p 这个格子专门装"门牌号"
 *    4. NULL  —— 空白纸条, 没指向任何地址
 * ============================================================ */

#include <stdio.h>

int main(void)
{
    int  a  = 42;          /* 普通 int 变量 */
    int *p  = &a;          /* p 是指针, 装 a 的门牌号 */

    printf("a        的值     = %d\n",   a);
    printf("&a       (a 的地址) = %p\n",   &a);
    printf("p        (装地址)  = %p\n",   p);
    printf("*p       (那格的值) = %d\n\n", *p);

    /* 通过指针改 a 的值 */
    *p = 100;
    printf("*p = 100 之后, a = %d\n\n", a);

    /* NULL: 空白纸条 */
    int *q = NULL;
    printf("q        = %p    (NULL = 没指向任何地址)\n", q);

    return 0;
}
