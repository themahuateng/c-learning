/* =========================================================
 *  pointers_warmup1.c —— 第7课 Phase A: 指针 4 件套
 *  目标: 找回 `&` `*` `int *p` `NULL` 的手感
 *  留了 2 个空让你填: ___HERE_1___ 和 ___HERE_2___
 * ========================================================= */

#include <stdio.h>

int main(void)
{
    int  a  = 42;
    int *p;                     /* 指针格子, 准备装一个 int 的地址 */

    /* 空 1 ↓: 让 p 指向 a —— 用 "取地址" 那个符号          */
    p = &a;

    printf("a      = %d\n",   a);
    printf("&a     = %p\n",   &a);     /* a 的门牌号 */
    printf("p      = %p\n",   p);      /* p 里装的也是 a 的门牌号 */
    printf("*p     = %d\n\n", *p);     /* 通过门牌号开门, 拿出 a */

    /* 空 2 ↓: 让 p 指向的格子变成 100,然后打印 a 看变了没 */
    *p = 100;
    printf("改了之后 a = %d (应该=100)\n", a);

    /* NULL 是什么: 看一下, 不动它 */
    int *q = NULL;
    printf("q (NULL) = %p  (这就是 「空盒」 的样子)\n", q);

    return 0;
}