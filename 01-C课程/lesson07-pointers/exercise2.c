#include <stdio.h>

int main(void)
{
    int arr[5] = {10, 20, 30, 40, 50};

    /* 空 1 ↓: 用"指针写法"取出第 3 个数 (arr[2]) ——
     *   思路: 从数组首地址出发, 加上偏移, 然后解引用
     */
    printf("第 3 个数 (指针写法): %d\n", *(arr + 2));

    /* 空 2 ↓: 用"下标写法"取出第 3 个数 —— 直接 arr[] */
    printf("第 3 个数 (下标写法): %d\n", arr[2]);

    /* 给你看的证据: 数组名 arr 和 &arr[0] 是同一个地址 */
    printf("\narr (首地址) = %p\n", arr);
    printf("&arr[0]      = %p\n", &arr[0]);

    return 0;
}
