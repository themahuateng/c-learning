#include <stdio.h>

/* 函数: 想让它把 main 传进来的那个数加上 10 */
void add_ten(int *p)
{
    /* 空 1 ↓: 通过参数 p, 把"它指向的那格"加上 10
     *   提示: "读出那格, 加 10, 写回去"
     */
    *p = *p + 10;
}

int main(void)
{
    int x = 5;
    printf("调用前 x = %d\n", x);

    /* 空 2 ↓: 调用 add_ten, 你想让它改 x, 该传 x 的什么? */
    add_ten(&x);

    printf("调用后 x = %d (期望 15)\n", x);
    return 0;
}
