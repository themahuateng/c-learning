#include <stdio.h>

int main(int argc, char *argv[])
{
    /* 空 1 ↓: 判断"收到了几样东西" —— 不够 2 样, 说明用户没给名字
     *   填一个变量的名字, 它就是存"个数"的那个
     */
    if (argc < 2) {
        printf("用法: exercise4.exe 你的名字\n");
        return 0;
    }

    /* 空 2 ↓: 打印用户敲的第一个词 (程序名后面那个) */
    printf("你好, %s!\n", argv[1]);

    return 0;
}
