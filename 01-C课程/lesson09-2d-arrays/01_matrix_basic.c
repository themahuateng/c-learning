/* ============================================================
 *  01_matrix_basic.c —— 第 9 课：二维数组 4 件事
 *
 *  这一份要认的 4 件事:
 *    1. 声明  int a[2][3]        —— 2 行 3 列
 *    2. 初始化 {{1,2,3},{4,5,6}} —— 按行写最清楚
 *    3. 两层循环遍历             —— 外层行、内层列
 *    4. 按下标访问 a[i][j]       —— 行列都从 0 开始
 * ============================================================ */

#include <stdio.h>

int main(void)
{
    int a[2][3] = {{1, 2, 3}, {4, 5, 6}};

    printf("按下标直接访问:\n");
    printf("  a[0][0] = %d   a[0][2] = %d\n", a[0][0], a[0][2]);
    printf("  a[1][0] = %d   a[1][2] = %d\n", a[1][0], a[1][2]);

    printf("\n两层循环打印整张表:\n");
    for (int i = 0; i < 2; i++) {
        for (int j = 0; j < 3; j++) {
            printf("%3d", a[i][j]);
        }
        printf("\n");
    }

    /* 改一个格子, 只影响它自己 */
    a[1][1] = 99;
    printf("\n把 a[1][1] 改成 99 之后:\n");
    for (int i = 0; i < 2; i++) {
        for (int j = 0; j < 3; j++) {
            printf("%3d", a[i][j]);
        }
        printf("\n");
    }

    /* 没写到的位置自动补 0 */
    int b[2][3] = {{7}, {8, 9}};
    printf("\n部分初始化会自动补 0 (b):\n");
    for (int i = 0; i < 2; i++) {
        for (int j = 0; j < 3; j++) {
            printf("%3d", b[i][j]);
        }
        printf("\n");
    }

    return 0;
}
