/* ============================================================
 *  exercise1.c —— 第 9 课练习: 矩阵转置
 *
 *  目标: 读入一个 2 行 3 列的矩阵, 输出它的转置 (3 行 2 列)
 *        转置 = 行列互换
 *
 *  留了 2 个空: ___HERE_1___ 和 ___HERE_2___
 *  提示都在注释里, 自己读, 自己想
 * ============================================================ */

#include <stdio.h>

int main(void)
{
    int a[2][3];
    int t[3][2];        /* 转置后的结果: 3 行 2 列 */

    printf("请输入 2 行 3 列的数:\n");
    for (int i = 0; i < 2; i++) {
        for (int j = 0; j < 3; j++) {
            scanf("%d", &a[i][j]);
        }
    }

    /* 空 1 ↓: 把 a[i][j] 放到转置表 t 的正确位置
     *   提示: 行变列、列变行 —— 原来第 i 行第 j 列, 放到 t 的哪一格?
     */
    for (int i = 0; i < 2; i++) {
        for (int j = 0; j < 3; j++) {
            t[j][i] = a[i][j];
        }
    }
    
    /* 打印转置后的结果 —— 注意它是 3 行 2 列 */
    printf("转置之后:\n");
    for (int i = 0; i < 3; i++) {
        for (int j = 0; j < 2; j++) {
            /* 空 2 ↓: 打印 t 的第 i 行第 j 列 */
            printf("%d ", t[i][j]);
        }
        printf("\n");
    }

    return 0;
}
