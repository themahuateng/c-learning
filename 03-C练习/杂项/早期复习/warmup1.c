/* =========================================================
 *  warmup1.c —— 第 6 课数组复习：5 个成绩求总分与平均分
 *  目标：找回 "数组下标 + 累加" 的手感
 *  留了 2 个空让你填：___HERE_1___ 和 ___HERE_2___
 * ========================================================= */

#include <stdio.h>

int main(void)
{
    int    scores[5];   /* 存 5 个成绩 */
    int    sum = 0;
    double avg;

    printf("请输入 5 个成绩（空格或回车都行）：\n");

    /* --- 第一关：把 5 个数读进数组 --- */
    for (int i = 0; i < 5; i++) {
        printf("  第 %d 个：", i + 1);
        /*  ⬇ 空 1：把键盘上的整数存进 scores 的 "第 i 个" 元素  ⬇  */
        scanf("%d", &scores[0]);
    }

    /* --- 第二关：把数组里的数累加到 sum --- */
    for (int i = 0; i < 5; i++) {
        /*  ⬇ 空 2：取出 scores 的 "第 i 个" 元素，加到 sum 上  ⬇  */
        sum += scores[i];
    }

    avg = sum / 5.0;        /* 5.0 保证结果是 double,保留小数 */
    printf("\n总分   = %d\n", sum);
    printf("平均分 = %.2f\n", avg);

    return 0;
}